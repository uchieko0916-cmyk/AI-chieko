import type { StoredRule } from '../types'
import { literalRule } from './helpers'

/** ら抜き言葉（「られる」の「ら」が抜けた表現） */
const PAIRS: [wrong: string, right: string][] = [
  ['食べれる', '食べられる'],
  ['見れる', '見られる'],
  ['来れる', '来られる'],
  ['出れる', '出られる'],
  ['起きれる', '起きられる'],
  ['寝れる', '寝られる'],
  ['着れる', '着られる'],
  ['考えれる', '考えられる'],
  ['決めれる', '決められる'],
  ['変えれる', '変えられる'],
  ['教えれる', '教えられる'],
  ['覚えれる', '覚えられる'],
  ['逃げれる', '逃げられる'],
  ['信じれる', '信じられる'],
  ['受けれる', '受けられる'],
  ['続けれる', '続けられる'],
  ['止めれる', '止められる'],
  ['開けれる', '開けられる'],
  ['閉めれる', '閉められる'],
]

export const raNukiRules: StoredRule[] = PAIRS.map(([wrong, right], i) =>
  literalRule(
    `ra-nuki-${i + 1}`,
    'ら抜き言葉',
    `「${wrong}」はら抜き言葉の可能性があります。`,
    wrong,
    right,
    'info',
  ),
)
